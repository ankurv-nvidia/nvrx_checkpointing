"""Write one manual-run JET workflow per platform, with a checkbox for each of its workloads."""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(REPO_ROOT / "ci"), str(REPO_ROOT / "ci" / "jet")]

import generate_workloads  # noqa: E402
from workload_matrix import JET_PLATFORMS, JetPlatform  # noqa: E402

WORKFLOWS_DIR = REPO_ROOT / ".github" / "workflows"
SUITE_ORDER = ("default", "main-branch-runs", "large-scale", "nvrx", "optional")
# GitHub accepts at most this many inputs on a manually run workflow.
MAX_INPUTS = 25
WHEEL_TASKS = {"aarch64": "wheel-aarch64", "x86_64": "wheel"}

HEADER = """\
# Generated by ci/github/generate_jet_workflows.py from ci/jobs.json; rerun it after changing workloads.
name: JET {platform}

on:
  workflow_dispatch:
    inputs:
"""

INPUT = """\
      {key}:
        description: {key} ({suite})
        type: boolean
        default: false
"""

JOBS = """
permissions:
  contents: read

jobs:
  select:
    runs-on: [self-hosted, jet]
    timeout-minutes: 10
    outputs:
      workloads: ${{{{ steps.select.outputs.workloads }}}}
    steps:
      - uses: actions/checkout@v7
      - id: select
        run: ci/github/jet.sh select
        env:
          JET_INPUTS: ${{{{ toJSON(inputs) }}}}

  wheel:
    needs: select
    runs-on: [self-hosted, build]
    timeout-minutes: 180
    outputs:
      artifact-id: ${{{{ steps.upload.outputs.artifact-id }}}}
    steps:
      - uses: actions/checkout@v7
      - run: ci/github/tasks.sh {wheel_task}
      - id: upload
        uses: actions/upload-artifact@v7
        with:
          name: wheel-{architecture}
          path: dist/
          retention-days: 7

  jet:
    needs: [select, wheel]
    uses: ./.github/workflows/jet.yml
    with:
      platform: {platform}
      workloads: ${{{{ needs.select.outputs.workloads }}}}
      wheel-{architecture}-artifact-id: ${{{{ needs.wheel.outputs.artifact-id }}}}
    secrets: inherit
"""

def platforms() -> list[JetPlatform]:
    """JET platforms that have at least one supported workload."""
    return [platform for platform in JET_PLATFORMS if workloads(platform)]


def workloads(platform: JetPlatform) -> list[generate_workloads.Workload]:
    """Every supported workload of a platform, grouped by suite in rollout order."""
    supported, _unsupported = generate_workloads.select_workloads(platform)
    return sorted(supported, key=lambda workload: SUITE_ORDER.index(workload.pipeline_suite))


def workflow_path(platform: JetPlatform) -> Path:
    return WORKFLOWS_DIR / f"jet-{platform.name}.yml"


def render(platform: JetPlatform) -> str:
    selected = workloads(platform)
    if len(selected) > MAX_INPUTS:
        raise ValueError(f"{platform.name} has {len(selected)} workloads; a manual-run form holds at most {MAX_INPUTS}")
    inputs = "".join(INPUT.format(key=workload.display_name, suite=workload.pipeline_suite) for workload in selected)
    jobs = JOBS.format(
        platform=platform.name,
        architecture=platform.architecture,
        wheel_task=WHEEL_TASKS[platform.architecture],
    )
    return HEADER.format(platform=platform.name) + inputs + jobs


def main() -> int:
    for platform in platforms():
        workflow_path(platform).write_text(render(platform))
        print(f"wrote {workflow_path(platform).relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
