"""Generate the complete static GitLab CI configuration.

Run this script locally after changing the platform matrix or CI template.
GitLab consumes the committed output and does not run this generator.
"""

from __future__ import annotations

import argparse
import json
import logging
import re
import sys
from pathlib import Path

logger = logging.getLogger(__name__)

HERE = Path(__file__).resolve().parent
TEMPLATE_CI = HERE / "gitlab-ci-native.template.yml"
OUTPUT_CI = HERE / "gitlab-ci-native.yml"
# The job matrix: one entry per hardware platform, consumed by _emit_platform
# and _emit_multinode. Editing which jobs exist needs no change to this script.
JOBS_FILE = HERE / "jobs.json"
BASELINES_DIR = HERE / "baselines"
STAGE_MARKER = "# >>> generate-ci.py: workload stages <<<"
JOB_MARKER = "# >>> generate-ci.py: workload jobs <<<"
GENERATED_HEADER = """\
# AUTO-GENERATED by ci/generate-ci.py from ci/gitlab-ci-native.template.yml.
# Edit the template or PLATFORMS matrix, then rerun the generator.

"""

# Pattern that identifies obsolete multi-node pico baseline files.
_MULTINODE_PICO_BASELINE_RE = re.compile(r"_pico_[2-9]\d*x\d+")


# One dict per hardware platform; keys are consumed in _emit_platform / _emit_multinode.
PLATFORMS = json.loads(JOBS_FILE.read_text())["platforms"]


def _job(  # noqa: PLR0913
    name: str,
    extends: list[str],
    *,
    job_args: str | None = None,
    stage: str | None = None,
    timeout: str | None = None,
    needs: tuple[tuple[str, bool], ...] = (),
    tags: tuple[str, ...] = (),
) -> str:
    """Render one concrete job block."""
    lines = [f'"{name}":', f"  extends: [{', '.join(extends)}]"]
    if stage is not None:
        lines.append(f"  stage: {stage}")
    if timeout is not None:
        lines.append(f"  timeout: {timeout}")
    if tags:
        lines.append(f"  tags: [{', '.join(tags)}]")
    if needs:
        lines.append("  needs:")
        for need, artifacts in needs:
            lines += [f"    - job: {need}", f"      artifacts: {str(artifacts).lower()}"]
    if job_args is not None:
        lines += ["  variables:", f'    JOB_ARGS: "{job_args}"']
    return "\n".join(lines)


# Above eight nodes a synchronous save costs more than a run can afford.
ASYNC_FROM_NODES = 16

GROUPS = (
    "native-deterministic",
    "native-perf",
    "nvrx-deterministic",
    "nvrx-perf",
    "valgrind",
    "16node-super3bf16",
    "16node-super3fp4",
    "64node-ultra3bf16",
    "64node-ultra3fp8",
    "8node-nano3",
)

FLAVOR_LABEL = {"detr": "[DETR]", "perf": "[PERF]"}
# Pipeline stages spell out what a terse flavor name abbreviates.
GROUP_FLAVOR = {"detr": "deterministic"}
OPTIONAL_GROUPS = frozenset(GROUPS) - {"native-deterministic", "native-perf"}


def _provider(job: str) -> str:
    """The provider a job writes through; the job is named for it."""
    return job


def _pretrain_group(job: str, flavor: str) -> str:
    """Default group for a single-node or 2-node pretrain job: <provider>-<flavor>."""
    return f"{_provider(job)}-{GROUP_FLAVOR.get(flavor, flavor)}"


def _add_job(  # noqa: PLR0913
    groups: dict[str, list[str]],
    bundle_jobs: dict[str, list[str]],
    group: str,
    name: str,
    extends: list[str],
    *,
    pipeline_suite: str | None = None,
    **kwargs: object,
) -> None:
    pipeline_suite = pipeline_suite or ("main-branch-runs" if group == "valgrind" else None)
    if pipeline_suite:
        extends = [*extends, f".{pipeline_suite.replace('-', '_')}_pipeline"]
    elif group in OPTIONAL_GROUPS:
        extends = [*extends, ".manual_optional"]
    stage = group if group in OPTIONAL_GROUPS else None
    groups[group].append(_job(name, extends, stage=stage, **kwargs))
    bundle_jobs[pipeline_suite or "default"].append(name)


def _emit_multinode(
    p: dict,
    runner: str,
    groups: dict[str, list[str]],
    bundle_jobs: dict[str, list[str]],
) -> None:
    """Emit each multinode entry's jobs into their group (pinned "group" or provider+flavor)."""
    for entry in p.get("multinode", []):
        timeout = entry.get("timeout")
        run_seg = f"{entry['config']}_{entry['scale']}"
        for job, flavor in entry["jobs"]:
            flavors = [flavor] if isinstance(flavor, str) else list(flavor)
            label = FLAVOR_LABEL.get(flavors[0], flavors[0])
            modifiers = "".join(f":{modifier}" for modifier in flavors[1:])
            name = f"{label}:{p['name']}:{_provider(job)}:{run_seg}{modifiers}"
            provider, common = job, "+".join(flavors)
            # Those jobs name the asynchronous writer outright. An entry names
            # the staging a given flavor wants when the default does not suit
            # it, so one flavor's staging changes without moving the other's.
            if entry["nodes"] >= ASYNC_FROM_NODES:
                common += "+" + entry.get("staging", {}).get(flavors[0], "async")
            flavor_flags = (
                f"--flavor {common} --run=ref:nvrx --run=cmp:{provider}"
                if flavors[0] == "detr" and "vg" not in flavors
                else f"--flavor {common}+{provider}"
            )
            flavor_args = entry.get("flavor_args", {}).get(flavors[0], "")
            args = " ".join(
                part
                for part in (
                    f"--nodes {entry['nodes']} --config {entry['config']}",
                    flavor_flags,
                    flavor_args,
                )
                if part
            )
            if flavors[0] == "perf" and (interval := entry.get("checkpoint_interval")):
                args += f" --checkpoint-interval {interval}"
            # Per-entry job-array override: NVLink-domain nodes per array task;
            # 0 keeps the classic single-allocation launch for a wide job.
            if (segment := entry.get("job_array_segment")) is not None:
                args += f" --job-array-segment {segment}"
            g = entry.get("group") or _pretrain_group(job, flavors[0])
            provider = _provider(job)
            suite = (
                "main-branch-runs"
                if "vg" in flavors
                else p.get("pipeline_suite") or ("nvrx" if provider == "nvrx" else entry.get("pipeline_suite"))
            )
            _add_job(
                groups,
                bundle_jobs,
                g,
                name,
                [".slurm_job", runner],
                pipeline_suite=suite,
                job_args=args,
                needs=p.get("native_wheel_needs", ())
                if suite is None and provider == "native" and "vg" not in flavors
                else (),
                tags=(p["name"], f"{entry['nodes']}n"),
                timeout=timeout,
            )


def _emit_platform(p: dict, groups: dict[str, list[str]], bundle_jobs: dict[str, list[str]]) -> None:
    """Emit every job for one platform into its group."""
    runner = f".runner_{p['name']}"
    name, gpus = p["name"], p["gpus"]
    if not p["has_image"]:
        return

    standard = [
        ("native", "detr"),
        ("native", "perf"),
        ("nvrx", "detr"),
    ]
    for job, flavor in standard:
        jname = f"{FLAVOR_LABEL.get(flavor, flavor)}:{name}:{_provider(job)}:pico_{gpus}"
        args = (
            f"--config pico --flavor {flavor} --run=ref:nvrx --run=cmp:{job}"
            if flavor == "detr"
            else f"--config pico --flavor {flavor}+{job}"
        )
        g = _pretrain_group(job, flavor)
        provider = _provider(job)
        _add_job(
            groups,
            bundle_jobs,
            g,
            jname,
            [".slurm_job", runner],
            pipeline_suite=p.get("pipeline_suite") or ("nvrx" if provider == "nvrx" else None),
            job_args=args,
            needs=p.get("native_wheel_needs", ()) if provider == "native" else (),
            tags=(name, "1n"),
        )

    # Valgrind is a correctness gate, not a performance baseline.
    vg = f"{name}:valgrind:pico_{gpus}"
    _add_job(
        groups,
        bundle_jobs,
        "valgrind",
        vg,
        [".slurm_job", runner],
        job_args="--config pico --flavor detr+vg+native",
        tags=(name, "1n"),
    )

    # nvrx perf smoke; no baseline (emits checkpoint times, not parseable bw metrics).
    nvrx_perf = f"{FLAVOR_LABEL['perf']}:{name}:nvrx:pico_{gpus}"
    _add_job(
        groups,
        bundle_jobs,
        "nvrx-perf",
        nvrx_perf,
        [".slurm_job", runner],
        pipeline_suite=p.get("pipeline_suite") or "nvrx",
        job_args="--config pico --flavor perf+nvrx",
        tags=(name, "1n"),
    )

    _emit_multinode(p, runner, groups, bundle_jobs)


def _baseline_bundle(suite: str, dependencies: list[str]) -> str:
    name = f"baseline-artifacts:{suite}"
    lines = [f'"{name}":', "  extends: .baseline_bundle", "  when: always", "  dependencies:"]
    lines.extend(f'    - "{dependency}"' for dependency in dependencies)
    lines += ["  rules:"]
    if suite == "default":
        lines += [
            '    - if: \'$PIPELINE_SUITE == "nvrx" || $PIPELINE_SUITE == "large-scale" || $PIPELINE_SUITE == "main-branch-runs"\'',
            "      when: never",
            "    - when: always",
        ]
    else:
        lines += [
            f'    - if: \'$PIPELINE_SUITE == "{suite}"\'',
            "      when: always",
            "    - when: never",
        ]
    return "\n".join(lines)


def _validate_platforms() -> None:
    """Raise SystemExit for known invalid platform-matrix configurations."""
    for p in PLATFORMS:
        for entry in p.get("multinode", []):
            if entry.get("config") == "pico":
                raise SystemExit(
                    f"{p['name']}: pico must run on exactly 1 node; "
                    f"entry {entry['key']!r} has nodes={entry.get('nodes')}",
                )
    for baseline in sorted(BASELINES_DIR.glob("*.yaml")):
        if _MULTINODE_PICO_BASELINE_RE.search(baseline.stem):
            raise SystemExit(
                f"obsolete multi-node pico baseline: {baseline.name}; "
                f"remove it or rename to 1-node form",
            )


def _render() -> str:
    _validate_platforms()
    template = TEMPLATE_CI.read_text()
    for marker in (STAGE_MARKER, JOB_MARKER):
        if template.count(marker) != 1:
            raise SystemExit(f"{TEMPLATE_CI}: expected exactly one {marker!r}")

    groups: dict[str, list[str]] = {group: [] for group in GROUPS}
    bundle_jobs: dict[str, list[str]] = {
        suite: [] for suite in ("default", "nvrx", "large-scale", "main-branch-runs")
    }
    for platform in PLATFORMS:
        _emit_platform(platform, groups, bundle_jobs)

    sections = [f"# {group}\n\n" + "\n\n".join(groups[group]) for group in GROUPS if groups[group]]
    sections.append(
        "# baseline artifacts\n\n"
        + "\n\n".join(_baseline_bundle(suite, dependencies) for suite, dependencies in bundle_jobs.items()),
    )
    jobs = "\n\n".join(sections)
    stages = "\n".join([*(f"  - {group}" for group in GROUPS if group in OPTIONAL_GROUPS), "  - baseline-artifacts"])
    rendered = template.replace(STAGE_MARKER, f"{STAGE_MARKER}\n{stages}")
    return GENERATED_HEADER + rendered.replace(JOB_MARKER, f"{JOB_MARKER}\n\n{jobs}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed YAML is stale")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO)
    rendered = _render()
    if args.check:
        if not OUTPUT_CI.exists() or OUTPUT_CI.read_text() != rendered:
            logger.error("%s is stale; run %s", OUTPUT_CI, Path(__file__).name)
            return 1
        logger.info("%s is up to date", OUTPUT_CI)
        return 0

    OUTPUT_CI.write_text(rendered)
    logger.info("wrote %s", OUTPUT_CI)
    return 0


if __name__ == "__main__":
    sys.exit(main())
